-- Меню на 7 дней: та же ротация двух блюд на приём пищи, что и в mock-данных
insert into public.plan_meals (plan_id, day, meal_title, dish_id)
select p.id, g.i, m.title, m.pool[((g.i - 1 + p.seed + m.off) % 2) + 1]
from (values
  ('veg',     0, array['d9','d10'],  array['d11','d12'], array['d13','d14'], array['d15','d16']),
  ('lowcarb', 1, array['d17','d18'], array['d19','d20'], array['d21','d22'], array['d23','d24']),
  ('sport',   2, array['d25','d26'], array['d27','d28'], array['d29','d30'], array['d31','d32'])
) as p(id, seed, breakfast, lunch, snack, dinner)
cross join generate_series(1, 7) as g(i)
cross join lateral (values
  ('Завтрак', p.breakfast, 0),
  ('Обед',    p.lunch,     1),
  ('Перекус', p.snack,     0),
  ('Ужин',    p.dinner,    1)
) as m(title, pool, off)
on conflict (plan_id, day, meal_title) do nothing;
