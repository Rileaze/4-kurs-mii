insert into public.plan_meals (plan_id, day, meal_title, dish_id)
select p.id, g.i, m.title, m.pool[((g.i - 1 + p.seed + m.off) % 2) + 1]
from (values ('light', 0), ('balance', 1), ('mass', 2)) as p(id, seed)
cross join generate_series(1, 7) as g(i)
cross join (values
  ('Завтрак', array['d1','d2'], 0),
  ('Обед',    array['d3','d4'], 1),
  ('Перекус', array['d5','d6'], 0),
  ('Ужин',    array['d7','d8'], 1)
) as m(title, pool, off);
