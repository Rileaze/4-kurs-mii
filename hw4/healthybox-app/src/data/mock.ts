function buildDays(seed: number, pools: MealPools): MenuDay[] {
  return Array.from({ length: 7 }, (_, i) => {
    const n = i + seed;
    return {
      day: i + 1,
      meals: [
        { title: 'Завтрак', dish: pools.breakfast[n % 2] },
        { title: 'Обед', dish: pools.lunch[(n + 1) % 2] },
        { title: 'Перекус', dish: pools.snack[n % 2] },
        { title: 'Ужин', dish: pools.dinner[(n + 1) % 2] },
      ],
    };
  });
}

